#pragma once

#include <M5Unified.h>

// 画面タッチを「タッチされた画面座標(px)」として取り出すだけの入力モジュール。
//
// タッチパネル固有の事情（`M5.Touch` の押下状態の判定・座標の取り出し方）をここに閉じ込め、
// 利用側へは「いまタッチされている点」だけを渡す。座標をどう使うか（視線を向ける・ボタン判定など）は
// このモジュールの責務ではないため、視線やアバターに関する知識は持たない。
class TouchInput {
public:
    // タッチされていれば、その画面座標(px, 左上原点)を (x,y) へ返して true。
    // タッチされていなければ false を返し、(x,y) は変更しない。
    // M5.Touch の状態は M5.update() が更新するため、必ずその後に呼ぶこと。
    //
    // 注: M5Stack Core2 は表示領域(240px)の下にボタン帯のタッチ領域があるため、y は 240 以上に
    // なりうる。範囲の扱いは用途によるので、ここではクランプせずそのまま返す。
    bool getPoint(int& x, int& y) const;
};
